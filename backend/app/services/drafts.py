def _s3p_rebuttal(matter: Matter, g: _Grounder) -> list[str]:
    p = matter.profile
    novelty = p.process_novelty or (
        "[state the technical advance — new process, novel extract, unexpected "
        "synergy, or new therapeutic effect]"
    )
    return [
        "## Submission — the claimed invention is not excluded under Section 3(p) / 3(e)",
        "",
        f"Re: examination of the application for **{matter.formulation_label or matter.title}**.",
        "",
        "### The exclusions relied on",
        "",
        "- Section 3(p) excludes an invention which is, in effect, traditional "
        "knowledge or an aggregation / duplication of known properties of "
        "traditionally known component(s)."
        + g.basis("Section 3(p) excludes traditional knowledge",
                  "traditional knowledge aggregation duplication known properties section 3(p)"),
        "- Section 3(e) excludes a substance obtained by mere admixture resulting "
        "only in the aggregation of the properties of its components."
        + g.basis("Section 3(e) excludes mere admixture",
                  "substance mere admixture aggregation properties components section 3(e)"),
        "",
        "### Why the claims fall outside these exclusions",
        "",
        f"1. **The technical contribution is not merely additive.** {novelty}",
        "2. **The effect is not a known property of the components.** [cite the "
        "comparative data / unexpected result in the specification].",
        "3. **The claim is to a specific process / composition, not to the "
        "traditionally known use.** [identify the claim(s)].",
        "4. **No single prior-art source discloses the claimed combination with "
        "the demonstrated effect.** [TKDL / prior-art search to be annexed — the "
        "assistant's TKDL cross-check is not yet connected].",
        "",
        "### Requested outcome",
        "",
        "Withdrawal of the Section 3(p) / 3(e) objection, or a hearing.",
    ]


_TEMPLATES = {
    DraftKind.form1: _form1,
    DraftKind.nba_abs: _nba_abs,
    DraftKind.disclosure_of_source: _disclosure_of_source,
    DraftKind.s3p_rebuttal: _s3p_rebuttal,
}


def render(matter: Matter, kind: DraftKind) -> RenderedDraft:
    info = KIND_INFO[kind]
    g = _Grounder(matter.jurisdiction.value)
    body = _TEMPLATES[kind](matter, g)
    lines = _header(matter, info.title) + body + _traceability(g)
    return RenderedDraft(
        kind=kind,
        title=info.title,
        markdown="\n".join(lines) + "\n",
        citations=list(g.used),
    )
