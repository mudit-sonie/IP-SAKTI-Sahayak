"""Cited document drafts (roadmap S8).

Templates for the paperwork an Ayurveda formulation actually needs on the way to
a filing. Each draft is filled from the matter's formulation profile and, for
every legal assertion it makes, carries a **[Legal basis: …]** marker resolved —
where the corpus supports it — to a real retrieved section. Nothing here is an
LLM generation: the structure is fixed, only the matter's own facts and the
grounded citations vary.

Drafts are skeletons for a professional to complete and verify — never a
ready-to-file document.
"""
