_DISCLAIMER = (
    "> **Draft skeleton — not a filing.** Generated by IP-SAKTI Sahayak from the "
    "matter's formulation profile. Every legal basis marker must be checked "
    "against the official section text. Complete the bracketed fields and have a "
    "registered patent agent / legal professional review before use. This is "
    "not legal advice."
)


@dataclass
class RenderedDraft:
    kind: DraftKind
    title: str
    markdown: str
    citations: list[Citation]


class _Grounder:
    """Resolve a legal-basis probe to a real citation, once per probe."""

    def __init__(self, jurisdiction: str) -> None:
        self._j = jurisdiction
        self._cache: dict[str, Citation | None] = {}
        self.used: list[Citation] = []

    def basis(self, claim: str, probe: str) -> str:
        """Return a '[Legal basis: …]' marker, grounded if the corpus supports it."""
        if probe not in self._cache:
            hits = _ground(probe, self._j)
            self._cache[probe] = hits[0] if hits else None
        cite = self._cache[probe]
        if cite is None:
            return f"  \n_[Legal basis: {claim} — verify the governing provision]_"
        if not any(
            c.source == cite.source and c.section == cite.section for c in self.used
        ):
            self.used.append(cite)
        stale = f" ⚠ may be amended by {cite.amended_by}" if cite.amended_by else ""
        return (
            f"  \n_[Legal basis: {cite.source}, Section {cite.section}{stale}]_"
        )


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _profile_lines(matter: Matter) -> list[str]:
    p = matter.profile
    return [
        f"- **Formulation:** {matter.formulation_label or 'not classified'}",
        f"- **Dosage form:** {p.dosage_form or '[dosage form]'}",
        "- **Key ingredients:** "
        + (", ".join(p.key_ingredients) if p.key_ingredients else "[ingredients]"),
        f"- **Intended use / claims:** {p.intended_use or '[intended use]'}",
        f"- **Asserted novelty:** {p.process_novelty or '[what is new]'}",
        f"- **Biological source / origin:** {p.source_notes or '[source and geographical origin]'}",
    ]


def _header(matter: Matter, title: str) -> list[str]:
    return [
        f"# {title}",
        "",
        _DISCLAIMER,
        "",
        f"**Matter:** {matter.title}  ",
        f"**Generated:** {_now()}  ",
        f"**Jurisdiction:** {matter.jurisdiction.value}",
        "",
        "## Formulation particulars",
        "",
        *_profile_lines(matter),
        "",
    ]


def _traceability(g: _Grounder) -> list[str]:
    out = ["", "## Traceability — legal bases cited", ""]
    if not g.used:
        out.append(
            "_No provision in the corpus met the citation bar for this draft. "
            "Each legal-basis marker above must be verified manually._"
        )
        return out
    for c in g.used:
        url = f" — {c.source_url}" if c.source_url else ""
        as_of = f" (text as of {c.as_of})" if c.as_of else ""
        amended = (
            f"  \n  ⚠ may have been amended by {c.amended_by}" if c.amended_by else ""
        )
        out.append(f"- {c.source}, Section {c.section}{as_of}{url}{amended}")
    return out


